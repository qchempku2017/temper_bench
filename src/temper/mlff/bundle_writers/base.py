"""Package inputs and a portable experiment record for an installed
runtime."""

from __future__ import annotations

import logging
from temper._version import __version__
from pathlib import Path, PurePosixPath
import shutil
from temper.utils.file_hashing import copy_verified, cache_dataset_hashes
from temper.job_management.paths import (
    bundle_root,
    bundle_directory,
    next_attempt,
)
from temper.utils.file_writing import store_lock

from temper.schemas.mlff_train_bundle import MLFFBundleFiles, MLFFTrainBundle
from temper.utils.defaults import (
    DEFAULT_MLFF_MODELS_DIR,
    DEFAULT_MLFF_TRAINING_INPUTS_DIR,
    DEFAULT_MLFF_TRAINING_OUTPUTS_DIR,
    DEFAULT_MLFF_TESTING_INPUTS_DIR,
    DEFAULT_MLFF_TESTING_OUTPUTS_DIR,
)

logger = logging.getLogger(__name__)


class MLFFBundleWriter:
    """Copy one bundle's inputs without changing its local source
    records.

    Parameters
    ----------
    bundle : MLFFTrainBundle
        Local experiment containing dataset and pretrained-model paths.
        Its MLFFSpec.file_layout supplies the native packaging filenames.
        The writer copies inputs for upload without consulting a spec
        builder or runtime adapter. Native configs are generated later
        on the execution machine.

    Attributes
    ----------
    bundle : MLFFTrainBundle
        Source experiment. Packaging returns an independent bundle with
        populated files and does not modify this object.
    """

    def __init__(self, bundle: MLFFTrainBundle) -> None:
        self.bundle: MLFFTrainBundle = bundle

    @cache_dataset_hashes()
    def write_submit_folder(
        self,
        target_dir: str | Path | None = None,
        *,
        bundle_write_root: str | Path | None = None,
    ) -> tuple[Path, MLFFTrainBundle]:
        """Write copied inputs, bundle.json, and a run.sh launcher.

        Native training configs and training scripts
        are generated by runtime preparation from this record and its
        copied inputs. Their paths are recorded here, but those files do
        not yet exist. We have to do this because the actual training and
        testing happens on a remote machine, and all paths must be resolved
        again on the remote machine.

        Test copies preserve their original filenames and relative subdirectories.
        The packaged training unit records the absolute original dataset root
        for local analysis. Users must keep those original split datasets
        unchanged at that location; uploaded copies are removed during cleanup.

        Parameters
        ----------
        target_dir : str, Path, or None
            Exact new directory to create, relative to the working directory
            when not absolute. None allocates a readable
            attempt below bundle_write_root. Existing directories are
            never replaced.
        bundle_write_root : str, Path or None, optional
            Root for automatic model/domain/bundle/attempt directories.
            Defaults to DEFAULT_BUNDLE_WRITE_ROOT or ./bundles, relative
            to the current directory. Mutually exclusive with
            target_dir.

        Returns
        -------
        tuple[Path, MLFFTrainBundle]
            Absolute submit-directory path and independent packaged
            bundle. The returned record matches bundle.json; the source
            is unchanged.

        Raises
        ------
        ValueError
            If both destination options are supplied, inputs or
            identities are invalid, or current packaging settings differ
            from the bundle's existing file locations. Existing
            locations must remain unchanged so all attempts can use the
            same shared bundle.
        OSError
            If inputs cannot be read or the destination cannot be
            created or written. An existing destination is never
            overwritten.
        """
        if target_dir is not None and bundle_write_root is not None:
            raise ValueError(
                "target_dir and bundle_write_root are mutually exclusive."
            )
        if target_dir is None:
            root = bundle_root(bundle_write_root)
            with store_lock(root):
                return self.write_submit_folder(
                    next_attempt(bundle_directory(root, self.bundle))
                )
        # Reconstruct nested models so in-place edits cannot retain
        # stale IDs.
        MLFFTrainBundle.model_validate(
            self.bundle.model_dump(), context={"verify_files": True}
        )
        unit = self.bundle.training_unit
        spec = self.bundle.mlff_spec
        layout = spec.file_layout
        logger.info(
            "Packaging bundle %s (%s, %s)",
            self.bundle.mlff_train_bundle_id,
            spec.mlff_type,
            self.bundle.unit_type,
        )

        # Pack training and testing I/O files.
        finetune = self.bundle.unit_type == "finetune"
        # Pack training inputs.
        training_inputs = (
            {
                key: f"{DEFAULT_MLFF_TRAINING_INPUTS_DIR}/{name}"
                for key, name in layout.training_input_filenames.items()
            }
            if finetune
            else {}
        )
        if finetune:
            training_inputs["train"] = (
                f"{DEFAULT_MLFF_TRAINING_INPUTS_DIR}/train.extxyz"
            )
            if unit.val_set is not None:
                training_inputs["validation"] = (
                    f"{DEFAULT_MLFF_TRAINING_INPUTS_DIR}/validation.extxyz"
                )
            else:
                training_inputs.pop("converted_validation", None)
        # Pack training outputs.
        training_outputs = (
            {
                key: f"{DEFAULT_MLFF_TRAINING_OUTPUTS_DIR}/{name}"
                for key, name in layout.training_output_filenames.items()
            }
            if finetune
            else {}
        )
        # Pack test inputs.
        testing_inputs = {
            filename: f"{DEFAULT_MLFF_TESTING_INPUTS_DIR}/{filename}"
            for filename in unit.test_sets
        }
        # Pack test outputs.
        testing_outputs = {
            filename: (
                f"{DEFAULT_MLFF_TESTING_OUTPUTS_DIR}/"
                f"{PurePosixPath(filename).with_suffix('.npz')}"
            )
            for filename in unit.test_sets
        }
        # Pack potential evaluation model.
        evaluation_model = (
            f"{DEFAULT_MLFF_TRAINING_OUTPUTS_DIR}/"
            f"{layout.evaluation_model_filename}"
            if finetune and layout.evaluation_model_filename is not None
            else None
        )
        files = MLFFBundleFiles(
            pretrained_model=(
                f"{DEFAULT_MLFF_MODELS_DIR}/"
                f"{layout.pretrained_model_filename}"
            ),
            training_input_files=training_inputs,
            training_output_files=training_outputs,
            test_input_files=testing_inputs,
            test_output_files=testing_outputs,
            evaluation_model=evaluation_model,
            training_stress=unit.training_has_stress,
            test_stress=unit.test_has_stress,
        )
        packaged = self.bundle.model_copy(deep=True)
        # Local analysis uses the original split root, regardless of where
        # the execution folder or the caller's working directory moves.
        packaged.training_unit.root_path = unit.root_path.expanduser().resolve()
        if self.bundle.files is not None and self.bundle.files != files:
            raise ValueError(
                "Bundle already packaged but previously specified "
                "file locations differ from the current settings. "
                "Use the original settings for further attempts."
            )
        packaged.files = files
        packaged.temper_version = __version__

        # Write into target directory.
        target = Path(target_dir).expanduser().absolute()
        target.mkdir(parents=True, exist_ok=False)
        try:
            # Write datasets.
            for filename in unit.test_sets:
                self._copy(
                    unit.resolve_local_dataset_path(filename),
                    target / files.test_input_files[filename],
                    unit.dataset_sha256.get(filename),
                )
            for key, filename in (
                ("train", unit.train_set),
                ("validation", unit.val_set),
            ):
                if filename is not None:
                    self._copy(
                        unit.resolve_local_dataset_path(filename),
                        target / files.training_input_files[key],
                        unit.dataset_sha256.get(filename),
                    )
            # Check hash and write pretrained model.
            artifact = spec.pretrained_model.artifacts["model"]
            source = artifact.path.expanduser().resolve()
            self._copy(
                source, target / files.pretrained_model, artifact.sha256
            )
            # Write the portable bundle record for instructing remote
            # pipeline runner.
            # Configuration files will be generated remotely by the
            # runner.
            packaged.to_json_file(target / "bundle.json")
            # One command calls pipeline.runner.run_pipeline: prepare,
            # fine-tune when requested,
            # then evaluate_mlff.run_test for every test dataset,
            # including zero-shot.
            (target / "run.sh").write_text(
                "#!/usr/bin/env bash\nset -euo pipefail\n"
                'cd -- "$(dirname -- "$0")"\n'
                "exec temper_bench run_pipeline bundle.json\n",
                encoding="utf-8",
                newline="\n",
            )
            (target / "run.sh").chmod(0o755)
        except Exception:
            shutil.rmtree(target)
            raise

        logger.info(
            "Wrote bundle %s to %s", packaged.mlff_train_bundle_id, target
        )
        return target, packaged

    @staticmethod
    def _copy(
        source: Path, destination: Path, expected: str | None = None
    ) -> None:
        logger.debug("Copying %s to %s", source, destination)
        destination.parent.mkdir(parents=True, exist_ok=True)
        if expected is None:
            shutil.copy2(
                source, destination
            )  # Legacy local packaging remains supported.
        else:
            copy_verified(source, destination, expected)
